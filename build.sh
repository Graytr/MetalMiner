#!/bin/zsh
# Builds Metal Miner in three pieces, so front-ends depend only on the engine's public interface:
#   MinerCore        library: harness, engine, and every algorithm folder (plug-ins, registered by folder)
#   metalminer       command line, linked against MinerCore
#   Metal Miner.app  SwiftUI app, linked against MinerCore (full build, or with --app)
# The Xcode toolchain is called by absolute path (no xcrun), and the module cache and temp files stay
# in .build/, so nothing is written outside this folder.
#
#   ./build.sh                   every algorithm folder, CLI and app   -> .build/all/
#   ./build.sh Ethash KawPow     just those folders, CLI only          -> .build/Ethash+KawPow/metalminer
#   ./build.sh --app Ethash      those folders, CLI and app
set -euo pipefail
ROOT="${0:A:h}"
DEV="$(xcode-select -p)"
TC="$DEV/Toolchains/XcodeDefault.xctoolchain/usr/bin"
SDK="$DEV/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk"

APP=0
ALGOS=()
for arg in "$@"; do
  if [[ "$arg" == "--app" ]]; then APP=1; else ALGOS+=("$arg"); fi
done
if (( ${#ALGOS} )); then
  NAME="${(j:+:)ALGOS}"
else
  for d in "$ROOT"/Sources/Algorithms/*(/N); do ALGOS+=("${d:t}"); done
  NAME=all
  APP=1
fi

OUT="$ROOT/.build/$NAME"
mkdir -p "$OUT/tmp" "$OUT/ModuleCache" "$OUT/modules"
export TMPDIR="$OUT/tmp" SDKROOT="$SDK" CLANG_MODULE_CACHE_PATH="$OUT/ModuleCache"
# Apple silicon only (the kernels assume its 32-wide SIMD groups), macOS 15 or later (every Apple silicon Mac runs it).
SWIFTC=("$TC/swiftc" -swift-version 5 -O -target arm64-apple-macos15.0 -sdk "$SDK" -module-cache-path "$OUT/ModuleCache")

CORE=("$ROOT"/Sources/Harness/*.swift "$ROOT"/Sources/Engine/*.swift(N))
for a in "${ALGOS[@]}"; do
  if [[ ! -d "$ROOT/Sources/Algorithms/$a" ]]; then
    print -u2 "no such algorithm folder: Sources/Algorithms/$a"
    exit 1
  fi
  CORE+=("$ROOT"/Sources/Algorithms/$a/**/*.swift(N))
done

REGISTRY="$OUT/GeneratedRegistry.swift"
{
  print "// Generated by build.sh from the algorithm folders in this build. Don't edit."
  for a in "${ALGOS[@]}"; do print "extension ${a}Family: AlgorithmFamily {}"; done
  print "enum GeneratedRegistry {"
  print "    static let families: [AlgorithmFamily.Type] = ["
  for a in "${ALGOS[@]}"; do print "        ${a}Family.self,"; done
  print "    ]"
  print "}"
} > "$REGISTRY"
CORE+=("$REGISTRY")

"${SWIFTC[@]}" -wmo -parse-as-library -module-name MinerCore -emit-library -static -o "$OUT/libMinerCore.a" \
  -emit-module -emit-module-path "$OUT/modules/MinerCore.swiftmodule" "${CORE[@]}"
"${SWIFTC[@]}" -I "$OUT/modules" -L "$OUT" -lMinerCore -o "$OUT/metalminer" "$ROOT"/Sources/CLI/*.swift
BUILT=".build/$NAME/metalminer"

if (( APP )); then
  BUNDLE="$OUT/Metal Miner.app"
  mkdir -p "$BUNDLE/Contents/MacOS" "$BUNDLE/Contents/Resources/Kernels"
  "${SWIFTC[@]}" -parse-as-library -I "$OUT/modules" -L "$OUT" -lMinerCore \
    -o "$BUNDLE/Contents/MacOS/MetalMiner" "$ROOT"/Sources/App/*.swift
  cp "$ROOT/Sources/App/Info.plist" "$BUNDLE/Contents/Info.plist"
  for k in "$ROOT"/Kernels/*.metal; do   # the app carries its own kernels, minus developer micro-benchmarks
    case "${k:t}" in *_lab.metal|*_prof.metal) ;; *) cp "$k" "$BUNDLE/Contents/Resources/Kernels/" ;; esac
  done
  ICON="$OUT/AppIcon.icns"
  if [[ ! -f "$ICON" ]]; then   # drawn once by Sources/Tools/MakeIcon.swift
    "${SWIFTC[@]}" -o "$OUT/make-icon" "$ROOT/Sources/Tools/MakeIcon.swift"
    "$OUT/make-icon" "$OUT/AppIcon.iconset"
    /usr/bin/iconutil -c icns -o "$ICON" "$OUT/AppIcon.iconset"
  fi
  cp "$ICON" "$BUNDLE/Contents/Resources/AppIcon.icns"
  # Ad-hoc signature so it runs on this Mac; releases need a Developer ID signature and notarization.
  /usr/bin/codesign --force --sign - "$BUNDLE" >/dev/null 2>&1
  BUILT="$BUILT and .build/$NAME/Metal Miner.app"
fi
print "built $BUILT (${#ALGOS} algorithm folder(s)${ALGOS:+: ${ALGOS[*]}})"
